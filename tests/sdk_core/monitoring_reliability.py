PREFIX = "以下是合成监控导出，本题只分析给定材料，不访问数据源。"


@dataclass(frozen=True)
class Case:
    scenario: Scenario
    criteria: str


def case(name: str, messages: tuple[str, ...], criteria: str) -> Case:
    return Case(
        Scenario(
            name="mrel_" + name,
            messages=tuple(("query", PREFIX + message) for message in messages),
            now=NOW,
        ),
        criteria,
    )


